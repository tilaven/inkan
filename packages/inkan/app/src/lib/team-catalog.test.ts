const slug = (name: string) => teamWords(name).join('-');
const themed = (name: string, motif: string) =>
  (motifKeywords()[motif] ?? []).some((k) => teamWords(name).some((w) => sameWord(w, k)));

describe('team catalogue', () => {
  it('gives every common team a themed motif on its own', () => {
    for (const name of TEAMS) {
      const style = assignStyles([{ id: slug(name), name }]).get(slug(name))!;
      expect(themed(name, style.motif), `${name} got ${style.motif}`).toBe(true);
    }
  });

  it('gives every common team a themed motif when they all share one site', () => {
    const styles = assignStyles(TEAMS.map((name) => ({ id: slug(name), name })));
    const misses = TEAMS.filter((name) => !themed(name, styles.get(slug(name))!.motif));
    expect(misses).toEqual([]);
  });
});
